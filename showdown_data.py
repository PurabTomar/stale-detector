def _is_valid_recorded_showdown(entry: Any) -> bool:
    """Validate that a showdown entry came from a real recorded run."""
    if not isinstance(entry, dict):
        return False
    if not entry.get("question") or not entry.get("recorded_at"):
        return False
    models = entry.get("models")
    if not isinstance(models, dict) or len(models) < 1:
        return False
    for m_key, m_val in models.items():
        if not isinstance(m_val, dict):
            return False
        if "legacy-llm" in str(m_key).lower():
            return False
        if not (m_val.get("raw_response") or m_val.get("answer")):
            return False
    return True


def get_saved_showdowns(
    path: Path | str | None = None,
) -> Dict[str, Dict[str, Any]]:
    """Load real recorded showdowns from `evidence/showdown_results.json`.

    Returns an empty dict `{}` when no real recorded file exists so the UI
    displays an honest empty state instead of fabricated comparisons.
    """
    target = Path(path) if path else SHOWDOWN_RESULTS_FILE
    if not target.is_file():
        return {}
    try:
        payload = json.loads(target.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    if not isinstance(payload, dict):
        return {}
    raw_showdowns = payload.get("showdowns")
    if not isinstance(raw_showdowns, dict):
        return {}

    recorded_date = str(payload.get("recorded_date") or "").strip()
    routing_mode = str(payload.get("routing_mode") or "").strip()
    valid: Dict[str, Dict[str, Any]] = {}
    for key, entry in raw_showdowns.items():
        if _is_valid_recorded_showdown(entry):
            merged = dict(entry)
            if recorded_date and not merged.get("recorded_date"):
                merged["recorded_date"] = recorded_date
            if routing_mode and not merged.get("routing_mode"):
                merged["routing_mode"] = routing_mode
            merged["source_label"] = (
                f"Saved ({merged.get('recorded_date') or 'recorded'})"
            )
            valid[key] = merged
    return valid


def get_saved_showdown(
    key: str,
    path: Path | str | None = None,
) -> Optional[Dict[str, Any]]:
    """Get a real recorded showdown by id/key, or None if unavailable."""
    return get_saved_showdowns(path=path).get(key)


def get_configured_showdown_models() -> List[str]:
    """Return 2-3 real configured models from active LLM routing config."""
    try:
        from llm import get_task_routing_summary

        summary = get_task_routing_summary()
    except Exception:
        return []

    candidates = [
        summary.get("judge_model"),
        summary.get("extract_model"),
        summary.get("dual_judge_secondary"),
        *(summary.get("fallbacks") or []),
    ]
    models: List[str] = []
    for cand in candidates:
        clean = str(cand or "").strip()
        if clean and clean not in models:
            models.append(clean)
        if len(models) >= 3:
            break
    return models


def run_live_showdown(
    question: str,
    models: Optional[List[str]] = None,
    max_claims: int = 5,
) -> Dict[str, Any]:
    """Execute a live Model Showdown against 2-3 real configured models.

    Measures real wall-clock latency via `time.perf_counter()` and records only
    token usage actually returned by the LLM API.
    """
    from extractor import extract_claims
    from llm import QA_SYSTEM_PROMPT, call_llm_with_meta, is_use_bifrost
    from verifier import compute_risk_weighted_overall_score, verify_claims

    clean_q = str(question or "").strip()
    if not clean_q:
        raise ValueError("Please enter a question to run a Model Showdown.")

    selected_models = list(models) if models else get_configured_showdown_models()
    if not selected_models:
        raise ValueError("No LLM models are configured for Model Showdown.")

    routing_mode = "bifrost" if is_use_bifrost() else "direct_gemini"
    recorded_at = datetime.now(timezone.utc).isoformat()
    recorded_date = datetime.now(timezone.utc).strftime("%b %d, %Y")
    model_results: Dict[str, Dict[str, Any]] = {}

    for m_name in selected_models:
        t0 = time.perf_counter()
        try:
            raw_answer, meta = call_llm_with_meta(
                system_prompt=QA_SYSTEM_PROMPT,
                user_prompt=clean_q,
                temperature=0.2,
                model_override=m_name,
            )
            answer_latency_ms = round((time.perf_counter() - t0) * 1000.0, 1)
            answered_model = str(meta.get("model_used") or m_name)
            total_tokens = int(meta.get("total_tokens") or 0) if (
                meta.get("usage_returned") or int(meta.get("total_tokens") or 0) > 0
            ) else None

            claims, _ = extract_claims(raw_answer)
            if max_claims > 0:
                claims = claims[:max_claims]
            verified = verify_claims(claims) if claims else []

            overall_score = compute_risk_weighted_overall_score(verified)
            status_counts = {
                "fresh": sum(1 for r in verified if r.get("status") == "fresh"),
                "outdated": sum(1 for r in verified if r.get("status") == "outdated"),
                "incorrect": sum(1 for r in verified if r.get("status") == "incorrect"),
                "partially_correct": sum(1 for r in verified if r.get("status") == "partially_correct"),
                "uncertain": sum(1 for r in verified if r.get("status") == "uncertain"),
                "unverifiable": sum(1 for r in verified if r.get("status") == "unverifiable"),
                "verification_failed": sum(1 for r in verified if r.get("status") == "verification_failed"),
            }

            model_results[m_name] = {
                "model_name": answered_model,
                "display_name": answered_model,
                "answer": raw_answer,
                "raw_response": raw_answer,
                "score": overall_score,
                "latency_ms": answer_latency_ms,
                "tokens": total_tokens,
                "status_counts": status_counts,
                "claims": verified,
                "error": None,
            }
        except Exception as exc:
            elapsed_ms = round((time.perf_counter() - t0) * 1000.0, 1)
            model_results[m_name] = {
                "model_name": m_name,
                "display_name": m_name,
                "answer": "",
                "raw_response": "",
                "score": None,
                "latency_ms": elapsed_ms,
                "tokens": None,
                "status_counts": {
                    "fresh": 0,
                    "outdated": 0,
                    "incorrect": 0,
                    "partially_correct": 0,
                    "uncertain": 0,
                    "unverifiable": 0,
                    "verification_failed": 0,
                },
                "claims": [],
                "error": str(exc),
            }

    winner_eval = evaluate_showdown_winner(model_results)
    return {
        "id": f"live-{int(time.time())}",
        "title": clean_q[:60],
        "question": clean_q,
        "description": f"Live comparison across {len(selected_models)} configured model(s) via {routing_mode}.",
        "recorded_at": recorded_at,
        "recorded_date": recorded_date,
        "routing_mode": routing_mode,
        "source_label": "Live",
        "models": model_results,
        "winner": winner_eval["winner"],
        "winner_score": winner_eval.get("winner_score"),
        "winner_reason": winner_eval["reason"],
    }


def evaluate_showdown_winner(model_results: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    """Evaluate the winner among models based on freshness score, stale claims, and latency.

    Returns plain-text `reason` (no raw markdown `**`) and HTML-safe `reason_html`.
    """
    if not model_results:
        return {
            "winner": "None",
            "winner_score": None,
            "reason": "No model results to evaluate.",
            "reason_html": "No model results to evaluate.",
            "disclaimer": SAMPLE_SIZE_DISCLAIMER,
        }

    scorable = [
        (name, data)
        for name, data in model_results.items()
        if isinstance(data, dict) and data.get("score") is not None and not data.get("error")
    ]
    if not scorable:
        return {
            "winner": "None",
            "winner_score": None,
            "reason": "No model returned a scorable result.",
            "reason_html": "No model returned a scorable result.",
            "disclaimer": SAMPLE_SIZE_DISCLAIMER,
        }

    sorted_models = sorted(
        scorable,
        key=lambda item: (
            item[1].get("score", 0),
            -item[1].get("status_counts", {}).get("outdated", 0),
            -item[1].get("status_counts", {}).get("incorrect", 0),
            -(item[1].get("latency_ms") if item[1].get("latency_ms") is not None else 999999),
        ),
        reverse=True,
    )

    winner_name, winner_data = sorted_models[0]
    runner_up_name, runner_up_data = (
        sorted_models[1] if len(sorted_models) > 1 else (None, None)
    )

    winner_score = int(winner_data.get("score", 0))
    if runner_up_data:
        runner_score = int(runner_up_data.get("score", 0))
        diff = winner_score - runner_score
        reason = (
            f"{winner_name} achieved the highest Freshness Score ({winner_score}/100), "
            f"+{diff} points higher than {runner_up_name} ({runner_score}/100)."
        )
        reason_html = (
            f"<strong>{html.escape(str(winner_name))}</strong> achieved the highest Freshness Score "
            f"({winner_score}/100), +{diff} points higher than "
            f"<strong>{html.escape(str(runner_up_name))}</strong> ({runner_score}/100)."
        )
    else:
        reason = f"{winner_name} scored {winner_score}/100 freshness."
        reason_html = f"<strong>{html.escape(str(winner_name))}</strong> scored {winner_score}/100 freshness."

    return {
        "winner": winner_name,
        "winner_score": winner_score,
        "reason": reason,
        "reason_html": reason_html,
        "disclaimer": SAMPLE_SIZE_DISCLAIMER,
    }
