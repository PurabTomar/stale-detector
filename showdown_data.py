"""Model Showdown module for Stale-Answer Detector.

Compares 2-3 real configured models side-by-side on freshness, outdated claims,
measured latency, and returned tokens using the exact same verification pipeline.

Saved showdowns are loaded ONLY from a real recorded run file
(`evidence/showdown_results.json`) generated by `scripts/generate_showdown.py`.
Unrecorded or fabricated data is never labeled "Saved".
"""

